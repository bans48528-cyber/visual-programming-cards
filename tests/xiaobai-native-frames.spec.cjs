const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const {command, matrixChunks, OP} = require('../xiaobai-protocol.js');

const root = path.resolve(__dirname, '..');
const cases = [];
const hex = bytes => Buffer.from(bytes).toString('hex');
const check = (expected, bytes, label) => cases.push(`${expected ? 'accept' : 'reject'}\t${hex(bytes)}\t${label}`);
const mutate = (source, offset, value) => {
  const bytes = Uint8Array.from(source);
  bytes[offset] = value;
  bytes[15] = bytes.slice(0, 15).reduce((sum, byte) => sum + byte, 0) & 255;
  return bytes;
};

// These three recorded packets independently pin the column layout and checksum.
const left = Array(64).fill(0), right = Array(64).fill(0);
for (const index of [0, 1, 62, 31]) left[index] = 1;
for (const index of [16, 55]) right[index] = 1;
const golden = matrixChunks(33, left, right).map((args, index) => command(index + 1, OP.SHOW_MATRIX, args));
assert.deepEqual(golden.map(hex), [
  '5a97980ac201432100000100000000bba5',
  '5a97980ac20243210180080400000048a5',
  '5a97980ac203432102000000400000fea5'
]);
golden.forEach((bytes, index) => check(true, bytes, `golden part ${index}`));

let seed = 0x43c2;
const randomPattern = () => Array.from({length: 64}, () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed >>> 31;
});
const patterns = [
  ['blank', Array(64).fill(0), Array(64).fill(0)],
  ['full', Array(64).fill(1), Array(64).fill(1)],
  ...Array.from({length: 16}, (_, index) => [`random ${index}`, randomPattern(), randomPattern()])
];
for (const [name, eyeLeft, eyeRight] of patterns) {
  for (const transfer of [0, 255]) {
    for (const seq of [1, 255]) {
      matrixChunks(transfer, eyeLeft, eyeRight).forEach((args, part) => {
        const bytes = command(seq, OP.SHOW_MATRIX, args);
        check(true, bytes, `${name}, transfer ${transfer}, seq ${seq}, part ${part}`);
        check(false, mutate(bytes, 5, 0), `${name}, zero sequence, part ${part}`);
      });
    }
  }
}
const fullFrames = matrixChunks(255, Array(64).fill(1), Array(64).fill(1))
  .map(args => command(255, OP.SHOW_MATRIX, args));
assert(fullFrames.some(bytes => bytes.slice(9, 15).includes(255)), 'exercise signed Java column bytes');

for (let part = 0; part < 3; part++) {
  const valid = fullFrames[part];
  for (const [offset, value] of [[0, 0], [1, 0x98], [2, 0x97], [3, 9], [4, 0xd2], [16, 0]])
    check(false, mutate(valid, offset, value), `bad envelope byte ${offset}, part ${part}`);
  const corruptChecksum = Uint8Array.from(valid);
  corruptChecksum[15] ^= 1;
  check(false, corruptChecksum, `bad checksum, part ${part}`);
  check(false, valid.slice(0, 16), `short frame, part ${part}`);
  check(false, [...valid, 0], `long frame, part ${part}`);
  for (const badPart of [3, 4, 127, 128, 255])
    check(false, mutate(valid, 8, badPart), `bad part ${badPart}, source part ${part}`);
  for (const opcode of [0, 6, 0x44, 0x80, 255])
    check(false, mutate(valid, 6, opcode), `unknown opcode ${opcode}, part ${part}`);
}
check(false, [], 'empty frame');
for (const offset of [13, 14]) {
  for (const value of [1, 128, 255])
    check(false, mutate(fullFrames[2], offset, value), `last part reserved byte ${offset} = ${value}`);
}

// Existing programming opcodes must continue to pass the production native gate.
const previousActions = [
  [OP.MOTOR_TIME, [0, 1, 232, 3, 0, 0]], [OP.MOVE_TIME, [1, 232, 3, 0, 0]],
  [OP.MOTOR_RUN, [0, 1]], [OP.WAIT_IR, [1, 0, 30]],
  [OP.MOTOR_STOP, [0]], [OP.MOTOR_POWER, [5]], [OP.MOVE_RUN, [1]], [OP.MOVE_POWER, [5]],
  [OP.SHOW_EYE, [1]], [OP.SHOW_NUM, [100]], [OP.PLAY_VOICE, [1]], [OP.WAIT_VOICE, [1]],
  [OP.MOVE_STOP, []], [OP.READ_IR, []], [OP.SHOW_OFF, []]
];
for (const [opcode, args] of previousActions) {
  for (const seq of [1, 255]) {
    const bytes = command(seq, opcode, args);
    check(true, bytes, `existing action ${opcode}, seq ${seq}`);
    check(false, mutate(bytes, 5, 0), `existing action ${opcode}, zero seq`);
    check(false, mutate(bytes, 7 + args.length, 1), `existing action ${opcode}, nonzero padding`);
  }
}
for (const opcode of [OP.ENTER_PROGRAM, OP.ENTER_REMOTE, OP.HEARTBEAT, OP.QUERY_STATUS, OP.STOP_PROGRAM]) {
  const bytes = command(0, opcode);
  check(true, bytes, `existing control ${opcode}`);
  check(false, mutate(bytes, 5, 1), `existing control ${opcode}, nonzero seq`);
  check(false, mutate(bytes, 7, 1), `existing control ${opcode}, nonzero padding`);
}

// Independent captured examples from the MCU contract, not generated by our opcode helpers.
// The handoff's stop_program vector uses seq 15; legacy controls require seq 0,
// so STOP remains covered by the existing-control regression above.
const learnedGolden = [
  ['query all', '5a97980ac20752443322110000000058a5'],
  ['learn slot 3', '5a97980ac208530403020103000000bda5'],
  ['cancel learning', '5a97980ac209540403020100000000bca5'],
  ['relearn slot 3', '5a97980ac20a530503020103010000c1a5'],
  ['declare run', '5a97980ac20a572a00000001000000e1a5'],
  ['wait slot 10', '5a97980ac20b55060302010a000000cba5'],
  ['next wait', '5a97980ac20c55070302010a000000cda5'],
  ['UID part 0', '5a97980ac20d560000000000000000b8a5'],
  ['UID part 1', '5a97980ac20e560100000000000000baa5'],
  ['finish run', '5a97980ac210572a00000000000000e6a5']
];
for (const [name, literal] of learnedGolden) {
  const bytes = Buffer.from(literal, 'hex');
  check(true, bytes, `MCU contract ${name}`);
  check(false, mutate(bytes, 5, 0), `MCU contract ${name}, zero seq`);
  for (const [offset, value] of [[0, 0], [1, 0x98], [2, 0x97], [3, 9], [4, 0xd2], [16, 0]])
    check(false, mutate(bytes, offset, value), `MCU contract ${name}, bad envelope ${offset}`);
  const corrupt = Uint8Array.from(bytes);
  corrupt[15] ^= 1;
  check(false, corrupt, `MCU contract ${name}, bad checksum`);
  check(false, bytes.slice(0, 16), `MCU contract ${name}, truncated`);
  check(false, [...bytes, 0], `MCU contract ${name}, too long`);
}

// qid/task/runId are nonzero uint32, including values with signed Java bytes.
// Check every ID byte independently so checking only the low byte cannot pass.
const numberedOps = [[0x52, []], [0x53, [1, 0]], [0x54, []], [0x55, [10]], [0x57, [1]]];
for (const [opcode, suffix] of numberedOps) {
  check(false, command(1, opcode, [0, 0, 0, 0, ...suffix]), `opcode ${opcode}, zero uint32`);
  for (let byte = 0; byte < 4; byte++) {
    for (const value of [1, 127, 128, 255]) {
      const id = [0, 0, 0, 0];
      id[byte] = value;
      for (const seq of [1, 255])
        check(true, command(seq, opcode, [...id, ...suffix]), `opcode ${opcode}, ID byte ${byte}=${value}, seq ${seq}`);
    }
  }
  check(true, command(255, opcode, [255, 255, 255, 255, ...suffix]), `opcode ${opcode}, max uint32`);
}

// Exercise all 256 slot/flag/part values rather than trusting JS validation.
for (let value = 0; value <= 255; value++) {
  check(value >= 1 && value <= 10, command(1, 0x53, [1, 0, 0, 0, value, 0]), `learn slot ${value}`);
  check(value >= 1 && value <= 10, command(1, 0x55, [1, 0, 0, 0, value]), `wait slot ${value}`);
  check(value <= 1, command(1, 0x53, [1, 0, 0, 0, 10, value]), `replace ${value}`);
  check(value <= 1, command(1, 0x57, [1, 0, 0, 0, value]), `run active ${value}`);
  check(value <= 1, command(1, 0x56, [value]), `UID part ${value}`);
}
for (const [opcode, args, reservedFrom] of [
  [0x52, [1, 0, 0, 0], 11], [0x53, [1, 0, 0, 0, 1, 0], 13],
  [0x54, [1, 0, 0, 0], 11], [0x55, [1, 0, 0, 0, 1], 12],
  [0x56, [0], 8], [0x57, [1, 0, 0, 0, 0], 12]
]) {
  for (let offset = reservedFrom; offset < 15; offset++) {
    for (const value of [1, 128, 255])
      check(false, mutate(command(1, opcode, args), offset, value), `opcode ${opcode}, reserved byte ${offset}=${value}`);
  }
}

// Use a complete JDK from the environment, the Android build cache, or PATH.
const cache = path.join(os.homedir(), '.cache', 'cards-android', 'jdk-ms');
const homes = [process.env.JAVA_HOME, process.env.JDK_HOME, process.env.JDK,
  ...(fs.existsSync(cache) ? fs.readdirSync(cache).map(name => path.join(cache, name)) : [])].filter(Boolean);
const extension = process.platform === 'win32' ? '.exe' : '';
const candidates = [...new Set(homes)].map(home => ({
  javac: path.join(home, 'bin', `javac${extension}`), java: path.join(home, 'bin', `java${extension}`)
}));
candidates.push({javac: `javac${extension}`, java: `java${extension}`});
const jdk = candidates.find(candidate => [candidate.javac, candidate.java].every(executable => {
  const probe = spawnSync(executable, ['-version'], {encoding: 'utf8', windowsHide: true});
  return !probe.error && probe.status === 0;
}));
assert(jdk, 'A JDK is required: set JAVA_HOME or install the cached Android JDK (javac and java).');

const tempRoot = path.resolve(os.tmpdir());
const classes = fs.mkdtempSync(path.join(tempRoot, 'xiaobai-native-frames-'));
const run = (executable, args, input) => {
  const result = spawnSync(executable, args, {cwd: root, input, encoding: 'utf8', windowsHide: true});
  if (result.error) throw result.error;
  assert.equal(result.status, 0, `${executable} failed:\n${result.stdout}\n${result.stderr}`);
  return result.stdout;
};
try {
  run(jdk.javac, ['-encoding', 'UTF-8', '-d', classes,
    path.join(root, 'android/app/src/main/java/com/cardprogramming/app/ProgramFrame.java'),
    path.join(__dirname, 'ProgramFrameTest.java')]);
  process.stdout.write(run(jdk.java, ['-cp', classes, 'com.cardprogramming.app.ProgramFrameTest'], cases.join('\n') + '\n'));
} finally {
  const target = path.resolve(classes);
  assert.equal(path.dirname(target), tempRoot, 'only remove this test’s own temporary class directory');
  assert(path.basename(target).startsWith('xiaobai-native-frames-'));
  fs.rmSync(target, {recursive: true, force: true});
}
