// The firmware C headers are authoritative. No private signing material is read.
'use strict';
const fs=require('node:fs'),path=require('node:path');
function contract(firmwareRoot){
 const header=fs.readFileSync(path.join(firmwareRoot,'Shared/Ota_Layout.h'),'utf8').replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g,'');
 const definitions=new Map([...header.matchAll(/^#define\s+(OTA_\w+)\s+([^\r\n]+)/gm)].map(m=>[m[1],m[2]]));
 const values={};
 function resolve(name,ancestors=[]){
  if(Object.hasOwn(values,name))return values[name];
  if(ancestors.includes(name)||!definitions.has(name))throw new Error(`Invalid OTA macro ${name}`);
  const expression=definitions.get(name).replace(/\b(0x[0-9a-f]+|\d+)[uUlL]*\b/gi,'$1'),tokens=expression.match(/0x[0-9a-f]+|\d+|[A-Za-z_]\w*|[()+-]/gi)||[];
  if(tokens.join('')!==expression.replace(/\s/g,''))throw new Error(`Unsupported OTA expression ${name}`);
  let pos=0;
  function atom(){const t=tokens[pos++];if(t==='('){const n=add();if(tokens[pos++]!==')')throw new Error('Missing parenthesis');return n;}
   if(/^(0x[0-9a-f]+|\d+)$/i.test(t||''))return Number(t);
   if(/^[A-Za-z_]\w*$/.test(t||''))return resolve(t,[...ancestors,name]);throw new Error(`Invalid macro atom ${t}`);}
  function add(){let n=atom();while(tokens[pos]==='+'||tokens[pos]==='-'){const op=tokens[pos++],right=atom();n=op==='+'?n+right:n-right;}return n;}
  const result=add();if(pos!==tokens.length||!Number.isSafeInteger(result)||result<0||result>0xffffffff)throw new Error(`Invalid macro value ${name}`);
  values[name]=result;return result;
 }
 for(const name of definitions.keys())resolve(name);
 const source=fs.readFileSync(path.join(firmwareRoot,'Shared/Ota_PublicKey.h'),'utf8'),initializer=source.match(/g_ota_public_key\s*\[64\]\s*=\s*\{([\s\S]*?)\}/)?.[1];
 if(!initializer)throw new Error('Public key initializer missing');
 const key=[...initializer.matchAll(/0x([0-9a-f]{2})/gi)].map(m=>m[1].toLowerCase()).join('');
 if(key.length!==128)throw new Error('Public key must be raw X||Y P-256');
 return {values,key};
}
function generated(firmwareRoot){
 const {values,key}=contract(firmwareRoot);
 return `// BEGIN GENERATED OTA CONTRACT\n  const LAYOUT=Object.freeze(${JSON.stringify(values,null,2).replace(/\n/g,'\n  ')});\n  const PUBLIC_KEY_HEX='${key}';\n  // END GENERATED OTA CONTRACT`;
}
function javaSource(values){
 const fields=Object.entries(values).map(([name,value])=>{
  const type=value>0x7fffffff?'long':'int',suffix=type==='long'?'L':'';
  return `    static final ${type} ${name}=0x${value.toString(16).padStart(8,'0')}${suffix};`;
 }).join('\n');
 return `package com.cardprogramming.app;\n\n// Generated by scripts/sync-ota-contract.cjs from Shared/Ota_Layout.h.\n// Never edit protocol constants here; change the authoritative firmware header and regenerate.\nfinal class OtaLayout {\n    private OtaLayout() {}\n${fields}\n}\n`;
}
function generatedJava(firmwareRoot){return javaSource(contract(firmwareRoot).values);}
if(require.main===module){
 const args=process.argv.slice(2),at=args.indexOf('--firmware'),firmware=at>=0?args[at+1]:path.resolve(__dirname,'../../../../5月/小白机器人/LBS-XIAOBAI-AI');
 if(!firmware)throw new Error('--firmware needs a directory');
 const target=path.resolve(__dirname,'../xiaobai-ota-protocol.js'),source=fs.readFileSync(target,'utf8');
 const pattern=/\/\/ BEGIN GENERATED OTA CONTRACT[\s\S]*?\/\/ END GENERATED OTA CONTRACT/;
 if(!pattern.test(source))throw new Error('Generated OTA contract markers missing in JS target');
 const updated=source.replace(pattern,generated(firmware));
 const nativeTarget=path.resolve(__dirname,'../android/app/src/main/java/com/cardprogramming/app/OtaLayout.java');
 const nativeSource=fs.existsSync(nativeTarget)?fs.readFileSync(nativeTarget,'utf8'):null,nativeUpdated=generatedJava(firmware);
 const changed=[];if(updated!==source)changed.push('xiaobai-ota-protocol.js');if(nativeSource!==nativeUpdated)changed.push('OtaLayout.java');
 if(!changed.length)console.log('JS/native OTA constants and public key match the firmware headers.');
 else if(args.includes('--check')){console.error(`OTA contract differs from firmware headers (${changed.join(', ')}); run sync-ota-contract.cjs before building.`);process.exitCode=1;}
 else{fs.writeFileSync(target,updated,'utf8');fs.writeFileSync(nativeTarget,nativeUpdated,'utf8');console.log('JS/native OTA contract and public key regenerated from firmware headers.');}
}
module.exports={contract,generated,javaSource,generatedJava};
